"""Write requirements.lock: every installed package pinned to its version and to its SHA-256 hashes.

    python -m venv .venv && .venv/bin/pip install -r requirements.txt     # a clean environment
    .venv/bin/python scripts/lock_requirements.py                         # needs network (pypi.org)
    pip install --require-hashes -r requirements.lock                     # what the container build uses

It lists what is installed in the interpreter that runs it (pip itself left out)
and asks PyPI for the hashes of every file published for that exact version, so
the lock works on Windows and Linux alike. Run it only from a clean environment
built from requirements.txt, or unrelated packages end up in the lock.

With --require-hashes pip refuses any package whose bytes differ from the lock,
and any package that is not in the lock at all (proposal section 3, supply chain).
"""
from __future__ import annotations

import json
import sys
from importlib import metadata
from pathlib import Path
from urllib import request

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"pip", "setuptools", "wheel"}
# Installed only on some systems; pip must not demand them elsewhere.
MARKERS = {"colorama": 'sys_platform == "win32"'}


def hashes(name: str, version: str) -> list[str]:
    with request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as resp:
        files = json.loads(resp.read())["urls"]
    return sorted({f["digests"]["sha256"] for f in files if not f.get("yanked")})


def main() -> int:
    dists = sorted({(d.metadata["Name"], d.version) for d in metadata.distributions()
                    if d.metadata["Name"] and d.metadata["Name"].lower() not in SKIP}, key=lambda t: t[0].lower())
    lines = ["# Generated by scripts/lock_requirements.py. Do not edit by hand.",
             f"# Python {sys.version_info.major}.{sys.version_info.minor}. Install with:",
             "#   pip install --require-hashes -r requirements.lock", ""]
    for name, version in dists:
        found = hashes(name, version)
        if not found:
            print(f"no files on PyPI for {name}=={version}", file=sys.stderr)
            return 1
        marker = f" ; {MARKERS[name.lower()]}" if name.lower() in MARKERS else ""
        lines.append(f"{name}=={version}{marker} \\")
        lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(found) - 1 else "") for i, h in enumerate(found)]
    (ROOT / "requirements.lock").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote requirements.lock: {len(dists)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
